import test from 'node:test';
import assert from 'node:assert/strict';
import { newAccount, normalizeAccount, growthUnlocked, growUnit, enhanceUnit, recruitUnits, recruitEarlyRabbit, applyGuideSequence, currentMission, claimMission, recordMissionBattle, completeChallenge } from '../dist/src/account.js';
const now = Date.UTC(2026,9,11,3);
function firstIdleDone() {
  const a = newAccount(now);
  a.onboarding.phase = 'complete';
  a.highestCleared = 1;
  a.owned.squirrel = true;
  a.sequence = ['sheep','squirrel',...Array(8).fill(null)];
  recordMissionBattle(a,{mode:'idle',stageId:1,won:true});
  claimMission(a);
  return a;
}
const reload = a => normalizeAccount(JSON.parse(JSON.stringify(a)),now);
test('wall loss, guaranteed free banner recruit, defense removal and first growth survive reload', () => {
  let a=firstIdleDone();
  a.fragments.sheep=3;
  const gold=a.gold, diamonds=a.diamonds;
  assert.equal(growUnit(a,'sheep'),false);
  assert.equal(enhanceUnit(a,'sheep'),false);
  assert.equal(recruitUnits(a,10,{free:true}),null);
  assert.equal(a.gold,gold);
  assert.equal(a.diamonds,diamonds);
  recordMissionBattle(a,{mode:'challenge',stageId:2,won:false});
  a=reload(a);
  assert.equal(a.earlyGuide.phase,'rabbit-recruit');
  const counters={...a.recruitment};
  assert.equal(recruitEarlyRabbit(a).unit.id,'rabbit');
  assert.equal(a.sequence[2],'rabbit');
  a=reload(a);
  assert.equal(recruitEarlyRabbit(a),null);
  assert.equal(a.fragments.rabbit,0);
  assert.deepEqual(a.recruitment,counters);
  assert.equal(a.diamonds,diamonds);
  a.sequence[2]=null; // Player removed the rabbit during manual preparation.
  completeChallenge(a,2);
  recordMissionBattle(a,{mode:'challenge',stageId:2,won:true});
  a=reload(a);
  assert.equal(a.earlyGuide.phase,'idle-defense');
  assert.ok(a.sequence.includes('rabbit'));
  claimMission(a);
  assert.equal(currentMission(a).id,'idle-second');
  assert.equal(growUnit(a,'sheep'),false);
  assert.equal(applyGuideSequence(a,['sheep','squirrel']),false);
  recordMissionBattle(a,{mode:'idle',stageId:1,won:false});
  assert.equal(a.earlyGuide.phase,'idle-defense');
  recordMissionBattle(a,{mode:'idle',stageId:2,won:false});
  a=reload(a);
  assert.equal(currentMission(a).title,'속공 토끼를 편성에서 빼기');
  assert.equal(applyGuideSequence(a,['sheep','rabbit']),false);
  assert.equal(applyGuideSequence(a,Array(10).fill(null)),false);
  a.sequence=['sheep','squirrel',...Array(8).fill(null)];
  assert.equal(applyGuideSequence(a,a.sequence),true);
  a=reload(a);
  assert.equal(a.earlyGuide.phase,'idle-retry');
  recordMissionBattle(a,{mode:'idle',stageId:2,won:true});
  a=reload(a);
  assert.equal(growthUnlocked(a),true);
  assert.equal(currentMission(a).completed,true);
  assert.equal(claimMission(a).id,'idle-second');
  assert.equal(currentMission(a).id,'growth-intro');
  assert.equal(currentMission(a).completed,false);
  assert.equal(growUnit(a,'sheep'),true);
  a=reload(a);
  assert.equal(currentMission(a).completed,true);
  assert.equal(claimMission(a).id,'growth-intro');
  assert.equal(currentMission(a).id,'challenge-3');
  recordMissionBattle(a,{mode:'idle',stageId:3,won:true});
  assert.equal(currentMission(a).id,'challenge-3');
  assert.equal(claimMission(a),null);
});
test('leveling before collecting idle reward keeps both tutorial missions claimable',()=>{
  const a=firstIdleDone();
  a.owned.rabbit=true;
  completeChallenge(a,2);
  a.earlyGuide.phase='growth';
  claimMission(a);
  growUnit(a,'sheep');
  assert.equal(currentMission(a).id,'idle-second');
  assert.equal(claimMission(a).id,'idle-second');
  assert.equal(claimMission(a).id,'growth-intro');
  assert.equal(currentMission(a).id,'challenge-3');
});
test('preexisting cleared or grown saves retain investments and bypass new tutorial',()=>{
  for (const progressed of ['stage','level']) {
    const raw=firstIdleDone();
    delete raw.earlyGuide;
    if(progressed==='stage')raw.highestCleared=5;
    else raw.levels.sheep=8;
    const a=reload(raw);
    assert.equal(a.earlyGuide.phase,'complete');
    assert.equal(a.earlyGuide.legacy,true);
    assert.equal(a.gold,raw.gold);
    assert.equal(a.levels.sheep,raw.levels.sheep);
    assert.equal(a.highestCleared,raw.highestCleared);
    assert.equal(growthUnlocked(a),true);
    assert.notEqual(currentMission(a).id,'idle-second');
  }
});
